export function advice(expected: string, heardAs?: string): string {
  if (heardAs && PAIR[`${expected}>${heardAs}`]) return PAIR[`${expected}>${heardAs}`];
  const g = GENERAL[expected] || GENERAL[expected.replace(/r$/, '')];
  if (heardAs) return `The /${expected}/ was closer to /${heardAs}/. ${g || ''}`.trim();
  return g ? `The /${expected}/ was unclear. ${g}` : `The /${expected}/ was unclear.`;
}

